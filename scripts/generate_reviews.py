def add_typo(text):
    """Добавляет лёгкую опечатку в 5% случаев."""
    if random.random() > 0.05:
        return text
    ops = random.choice(['swap', 'double', 'space'])
    if ops == 'swap' and len(text) > 10:
        i = random.randint(2, len(text) - 3)
        text = text[:i] + text[i+1] + text[i] + text[i+2:]
    elif ops == 'double' and len(text) > 5:
        i = random.randint(1, len(text) - 2)
        text = text[:i] + text[i] + text[i:]
    elif ops == 'space' and len(text) > 8:
        i = random.randint(3, len(text) - 4)
        text = text[:i] + " " + text[i:]
    return text


def pick_rating():
    return random.choices([5, 4, 3, 2, 1], weights=RATING_W, k=1)[0]


def build_date(idx, total, days_back):
    """
    Кластерные даты. Не равномерные.
    """
    # Базовый тренд: рост во времени
    t = idx / total
    base_days = int(days_back * (1 - t ** 0.7))

    # Кластеры: всплески в определённые периоды
    clusters = [30, 90, 150, 270, 400]
    if random.random() < 0.3:
        base_days = random.choice(clusters) + random.randint(-15, 15)

    # Шум
    base_days += random.randint(-20, 20)
    base_days = max(1, min(base_days, days_back))

    d = datetime.now(timezone.utc) - timedelta(days=base_days)
    # Будни и выходные: пики в будни
    if d.weekday() >= 5 and random.random() < 0.6:
        d -= timedelta(days=random.randint(1, 3))
    # Время суток
    hour = random.choices(range(24), weights=[
        1,1,1,1,1,2,3,5,8,10,10,9,8,7,7,8,9,10,10,9,7,5,3,2
    ], k=1)[0]
    d = d.replace(hour=hour, minute=random.randint(0, 59), second=random.randint(0, 59), microsecond=0)
    return d


def build_review(idx, total, days_back):
    """Собирает один отзыв."""
    # Услуга
    si = random.choices(range(5), weights=SERVICE_W, k=1)[0]
    sr, su = SERVICES_RU[si], SERVICES_UK[si]

    # Оценка
    rating = pick_rating()

    # Текст
    pool_ru = TEXTS_RU.get(sr, TEXTS_RU["Другое"]).get(rating, [])
    if not pool_ru:
        pool_ru = TEXTS_RU["Другое"][rating]
    text_ru = random.choice(pool_ru)

    # Опечатка
    text_ru = add_typo(text_ru)

    # Язык
    lang = random.choice(LANG_DIST)
    if lang == 'ru':
        name_ru = pick_name('ru')
        name_uk = ""
        text_uk = ""
    elif lang == 'uk':
        name_uk = pick_name('uk')
        name_ru = ""
        text_uk = text_ru  # упрощённо — в реальности был бы перевод
        text_ru = ""
    else:  # both
        name_ru = pick_name('ru')
        name_uk = to_uk_name(name_ru)
        text_uk = text_ru

    # Ответ
    reply_ru = None
    reply_uk = None
    if rating <= 4 and random.random() < 0.30:
        reply_ru = random.choice(REPLIES_RU)
        reply_uk = reply_ru

    # Дата
    date = build_date(idx, total, days_back)

    initial = ""
    if name_ru:
        initial = name_ru[0]
    elif name_uk:
        initial = name_uk[0]

    return {
        "id": f"r-{idx:04d}",
        "name_ru": name_ru,
        "name_uk": name_uk,
        "initial": initial,
        "service_ru": sr,
        "service_uk": su,
        "rating": rating,
        "date": date.strftime("%Y-%m-%d"),
        "text_ru": text_ru,
        "text_uk": text_uk,
        "reply_ru": reply_ru,
        "reply_uk": reply_uk
    }


def summary(reviews):
    total = len(reviews)
    if total == 0:
        return {"rating": 0, "total": 0, "distribution": {}}
    s = sum(r["rating"] for r in reviews)
    dist = {5:0,4:0,3:0,2:0,1:0}
    for r in reviews:
        dist[r["rating"]] += 1
    # Некруглые метрики
    rating = round(s / total + random.uniform(-0.03, 0.03), 2)
    rating = max(1.0, min(5.0, rating))
    return {
        "rating": rating,
        "total": total,
        "distribution": {str(k): v for k, v in dist.items()}
    }


