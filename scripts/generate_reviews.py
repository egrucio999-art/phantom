# пересчёт summary
def summary(reviews):
    total = len(reviews)
    dist = {5:0,4:0,3:0,2:0,1:0}
    s = 0
    for r in reviews:
        dist[r["rating"]] += 1
        s += r["rating"]
    return {"rating": round(s/total, 1), "total": total, "distribution": {str(k):v for k,v in dist.items()}}

