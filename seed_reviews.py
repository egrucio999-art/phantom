def pick_service():
    return random.choices(SERVICES, weights=SERVICE_WEIGHTS, k=1)[0]

def pick_rating():
    # 70% пятёрок, 15% четвёрок, 8% троек, 5% двоек, 2% единиц
    return random.choices([5,4,3,2,1], weights=[70,15,8,5,2], k=1)[0]

def pick_text(service, rating):
    if rating == 5:
        pool = POSITIVE.get(service, POSITIVE["Другое"])
    elif rating == 4:
        pool = MIXED_POSITIVE.get(service, MIXED_POSITIVE["Другое"])
    elif rating == 3:
        pool = NEUTRAL.get(service, NEUTRAL["Другое"])
    else:
        pool = NEGATIVE.get(service, NEGATIVE["Другое"])
    return random.choice(pool)

def pick_name():
    return random.choice(NAMES)

def pick_date(days_back_max=365):
    days = random.randint(1, days_back_max)
    dt = datetime.utcnow() - timedelta(days=days)
    # разброс по часам, чтобы даты не были одинаковыми
    dt = dt.replace(hour=random.randint(8,22), minute=random.randint(0,59), second=random.randint(0,59), microsecond=0)
    return dt.isoformat() + "Z"

def build_review(idx):
    service = pick_service()
    rating = pick_rating()
    text = pick_text(service, rating)
    name = pick_name()
    
    # 12% отзывов получают ответ компании — только на 1-4 звезды
    reply = None
    if rating <= 4 and random.random() < 0.25:
        reply = random.choice(REPLIES)
    
    # 95% одобрены, 5% ждут модерации
    approved = random.random() > 0.05
    
    return {
        "name": name,
        "service": service,
        "rating": rating,
        "text": text,
        "reply": reply,
        "approved": approved,
        "created_at": pick_date()
    }

# ─────────────────────────────────────────────────────────
# ЗАЛИВКА В SUPABASE
# ─────────────────────────────────────────────────────────

def push_batch(batch):
    payload = json.dumps(batch, ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(
        f"{SUPABASE_URL}/rest/v1/reviews",
        data=payload,
        headers={
            "apikey": SUPABASE_KEY,
            "Authorization": f"Bearer {SUPABASE_KEY}",
            "Content-Type": "application/json",
            "Prefer": "return=minimal"
        },
        method='POST'
    )
    try:
        with urllib.request.urlopen(req) as response:
            return response.status
    except urllib.error.HTTPError as e:
        print(f"HTTP {e.code}: {e.read().decode('utf-8', errors='replace')[:300]}")
        return e.code

def main():
    TOTAL = 1000
    BATCH = 100
    print(f"Генерация {TOTAL} отзывов...")
    reviews = [build_review(i) for i in range(TOTAL)]
    
    # сохраняем локально для бэкапа
    with open("reviews_seed.json", "w", encoding="utf-8") as f:
        json.dump(reviews, f, ensure_ascii=False, indent=2)
    print(f"Сохранено локально: reviews_seed.json ({TOTAL} шт.)")
    
    print("Заливка в Supabase...")
    total_ok = 0
    for i in range(0, TOTAL, BATCH):
        batch = reviews[i:i+BATCH]
        status = push_batch(batch)
        if status in (200, 201):
            total_ok += len(batch)
            print(f"  {total_ok}/{TOTAL} — ok")
        else:
            print(f"  ошибка на батче {i}-{i+len(batch)}")
            break
    print(f"Готово. Загружено: {total_ok}/{TOTAL}")

if __name__ == "__main__":
    main()
