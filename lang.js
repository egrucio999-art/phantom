  function detectLang(){
    const saved = localStorage.getItem(KEY);
    if(saved === 'ru' || saved === 'uk') return saved;
    const nav = (navigator.language || 'ru').toLowerCase();
    if(nav.startsWith('uk')) return 'uk';
    return 'ru';
  }
  
  function applyLang(lang){
    document.documentElement.lang = lang;
    localStorage.setItem(KEY, lang);
    
    // Текстовые элементы с data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const val = translations[lang][key];
      if(val === undefined) return;
      if(el.tagName === 'INPUT' || el.tagName === 'TEXTAREA'){
        if(el.placeholder !== undefined && el.dataset.i18nAttr === 'placeholder'){
          el.placeholder = val;
        } else {
          el.value = val;
        }
      } else {
        el.innerHTML = val;
      }
    });
    
    // Placeholder атрибуты
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.dataset.i18nPh;
      const val = translations[lang][key];
      if(val !== undefined) el.placeholder = val;
    });
    
    // Опции селектов
    document.querySelectorAll('[data-i18n-opt]').forEach(el => {
      const key = el.dataset.i18nOpt;
      const val = translations[lang][key];
      if(val !== undefined) el.textContent = val;
    });
    
    // Активная кнопка языка
    document.querySelectorAll('.lang-switch button').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
    
    // Сообщаем странице, что язык сменился (для рендера отзывов)
    document.dispatchEvent(new CustomEvent('langchange', {detail: {lang}}));
  }
  
  function switchLang(lang){
    if(lang !== 'ru' && lang !== 'uk') return;
    applyLang(lang);
  }
  
  window.PhantomLang = {
    current: detectLang,
    switch: switchLang,
    t: function(key){
      const lang = detectLang();
      return translations[lang][key] || key;
    }
  };
  
  // Применяем язык при загрузке
  document.addEventListener('DOMContentLoaded', () => {
    applyLang(detectLang());
    
    // Обработчик клика по переключателю
    document.addEventListener('click', e => {
      const btn = e.target.closest('.lang-switch button');
      if(!btn) return;
      e.preventDefault();
      switchLang(btn.dataset.lang);
    });
  });
